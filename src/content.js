/**
 * 応募締切。曜日は書かずに日付から導出する。
 * 手で「（火）」と書いていたが、2026年9月30日は水曜日だった。
 * 曜日・月日・時刻を別々の文字列で持つと、必ずどれかが取り残される。
 *
 * 本番は設定シートの「締切日時」が正。ここはその静的な控え。
 * 食い違ったらビルドを止める（src/build-pdf.js の verifyConfig）。
 */
const DEADLINE = (function () {
  const at = new Date('2026-09-30T18:00:00+09:00');
  const jst = new Date(at.getTime() + 9 * 3600 * 1000);   // UTC基準で日本時間の暦を読む
  const dow = '日月火水木金土'[jst.getUTCDay()];
  const m = jst.getUTCMonth() + 1, d = jst.getUTCDate();
  const hh = String(jst.getUTCHours()).padStart(2, '0') + ':'
           + String(jst.getUTCMinutes()).padStart(2, '0');
  return {
    at,
    time: hh,                                             // 18:00
    short: m + '.' + d,                                   // 9.30（紙面で大きく見せる）
    full: jst.getUTCFullYear() + '年' + m + '月' + d + '日（' + dow + '）' + hh,
    label: m + '月' + d + '日（' + dow + '）' + hh,
  };
})();

